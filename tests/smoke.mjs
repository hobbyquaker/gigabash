// Browser-Smoke-Test mit Screenshots. Aufruf: PW_PATH=<node_modules mit playwright-core> BROWSER_EXE=<firefox> node tests/smoke.mjs <abs. Pfad zu dist/oganesson.html> <Ausgabeordner> [breite höhe touch]
// Firefox, weil der Chromium-Renderer unter WSL abstürzt (keine Screenshots).
import { createRequire } from 'node:module';
import { join } from 'node:path';
const { firefox } = createRequire(join(process.env.PW_PATH || '.', 'x.js'))('playwright-core');
const [file, out, w = '540', h = '960', touch] = process.argv.slice(2);
const b = await firefox.launch({ executablePath: process.env.BROWSER_EXE });
const ctx = await b.newContext({ viewport: { width: +w, height: +h }, hasTouch: !!touch });
const page = await ctx.newPage();
const errs = [];
page.on('pageerror', (e) => errs.push('pageerror: ' + e.message));
page.on('console', (m) => { if (m.type() === 'error') errs.push('console: ' + m.text()); });
await page.goto(`file://${file}?debug${touch ? '&touch' : ''}`, { waitUntil: 'domcontentloaded' });
await page.waitForTimeout(1500);
const shot = async (n) => { await page.screenshot({ path: `${out}/${n}.png` }); console.log('shot', n); };
await shot('1-start');
await page.click('[data-act=start]');
await page.waitForTimeout(2500);
await page.keyboard.down('ArrowLeft'); await page.waitForTimeout(400); await page.keyboard.up('ArrowLeft');
await page.evaluate(() => { const s = window.oganesson.scene; s.sim.player.invuln = 1e9; s.debugStep(1500, { mx: 0, my: 0, bomb: false }); });
await page.waitForTimeout(600);
await shot('2-flight');
await page.evaluate(() => { const s = window.oganesson.scene; s.sim.player.gun = 5; s.debugStep(1200); });
await page.waitForTimeout(400);
await shot('3-flight2');
await page.evaluate(() => { const s = window.oganesson.scene; let i = 0; while (s.sim.phase !== 'boss' && i++ < 5000) s.debugStep(10); s.debugStep(300); });
await page.waitForTimeout(500);
await shot('4-boss');
await page.evaluate(() => { const s = window.oganesson.scene; s.sim.boss.hp = 50; });
await page.waitForTimeout(1500);
await shot('5-bossdown');
await page.evaluate(() => { const s = window.oganesson.scene; s.debugStep(400); });
await page.waitForTimeout(800);
await page.evaluate(() => { const s = window.oganesson.scene; s.sim.credits = 3000; s.sim.skillPoints = 2; s.sim.player.hull = 60; window.oganesson.ui.openShop(s.sim); });
await page.waitForTimeout(300);
await shot('6-shop-ship');
await page.click('[data-tab=weapons]');
await page.click('.buy[data-cmd*="side"]');
await page.click('[data-slot=core]');
await page.click('.buy[data-cmd*="drone"]');
await page.waitForTimeout(200);
await shot('7-shop-weapons');
await page.click('[data-tab=skills]');
await page.click('.node.avail');
await page.waitForTimeout(200);
await shot('8-shop-skills');
await page.click('[data-act=launch]');
await page.waitForTimeout(1200);
await page.evaluate(() => { const s = window.oganesson.scene; s.sim.player.invuln = 1e9; s.debugStep(900); });
await page.waitForTimeout(300);
await shot('9-sector2');
await page.evaluate(() => { const s = window.oganesson.scene; s.sim.player.invuln = 0; s.sim.player.hull = 1; s.sim.player.shield = 0; });
await page.evaluate(() => { const s = window.oganesson.scene; let i = 0; while (s.sim.phase !== 'over' && i++ < 3000) s.debugStep(5, { mx: 0, my: -100, bomb: false }); });
await page.waitForTimeout(2600);
await shot('10-gameover');
console.log('Fehler:', errs.length ? errs.join('\n') : 'keine');
await b.close();
